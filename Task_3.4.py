
# Создайте словарь со списком вещей для похода в качестве ключа и их массой в качестве значения. Определите какие вещи влезут в рюкзак передав его максимальную грузоподъёмность. Достаточно вернуть один допустимый вариант.*Верните все возможные варианты комплектации рюкзака.


import itertools

# Создаем словарь с вещами и их массой
вещи = {
    'палатка': 2,
    'спальный мешок': 1,
    'трекинговые палки': 0.5,
    'газовая горелка': 0.3,
    'котелок': 0.4,
    'еда': 1,
    'вода': 1.5,
    'перекусы': 0.5,
    'зажигалка': 0.1
}

# Функция для получения всех возможных вариантов комплектации рюкзака
def все_варианты_в_рюкзаке(вещи, грузоподъемность):
    варианты = []
    предметы = list(вещи.items())
    
    # Перебираем все возможные комбинации
    for i in range(1, len(предметы) + 1):
        for комбинация in itertools.combinations(предметы, i):
            общая_масса = sum(масса for _, масса in комбинация)
            if общая_масса <= грузоподъемность:
                варианты.append([предмет for предмет, _ in комбинация])
    
    return варианты

# Указываем максимальную грузоподъемность рюкзака
макс_грузоподъемность = 5

# Выводим все возможные варианты вещей, которые влезут в рюкзак
варианты = все_варианты_в_рюкзаке(вещи, макс_грузоподъемность)
for вариант in варианты:
    print(вариант)